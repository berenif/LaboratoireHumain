"""Compile the isolated inspector and inspect retained state; zero integrations.

Only a temporary /tmp shared library is built. The selected preset supplies
the original retained source session and pinned v9 helper, never a new model
or a state generated by this test. Missing retained assets are explicit skips.
"""
import ctypes as C
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

import numpy as np

from source_step_probe import World, ROOT, PTR, ptr


HERE = Path(__file__).resolve().parent
PRESET = json.loads((HERE/'source-step-selected-v1.json').read_text())
BASE = ROOT/PRESET['sourceSession']
HELPER = ROOT/PRESET['helper']
WHEEL = BASE/'dependency/official-wheel/mujoco'
EXPORTS = {'lh_ro_model', 'lh_ro_model_fingerprint', 'lh_ro_ground_contacts'}
HEADER = 64
STRIDE = 112
CAPACITY = HEADER+STRIDE*64


def checkpoint_bytes(world):
    size = world.l.lh_checkpoint_size(world.h)
    out = C.create_string_buffer(size)
    if world.l.lh_checkpoint_export(world.h, out, size) != size:
        raise AssertionError('retained native checkpoint export failed')
    return out.raw


class ContactInspection(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        required = [BASE/'source-model/humanoid_high_freq.xml',
                    BASE/'slow-continuation/final.bin', HELPER,
                    WHEEL/'include/mujoco.h',
                    WHEEL/'libmujoco_nogl.so.2.1.3']
        missing = [str(path) for path in required if not path.is_file()]
        if missing:
            raise unittest.SkipTest('retained selected-preset source assets absent: '+', '.join(missing))
        compiler = shutil.which('cc')
        nm = shutil.which('nm')
        if compiler is None or nm is None:
            raise unittest.SkipTest('local C compiler or nm absent; inspector not built')
        cls.nm = nm
        cls.temporary = tempfile.TemporaryDirectory(prefix='lh-contact-inspector-', dir='/tmp')
        cls.addClassCleanup(cls.temporary.cleanup)
        cls.inspector = Path(cls.temporary.name)/'source_contact_inspection.so'
        subprocess.run(['bash', str(HERE/'build_source_contact_inspection.sh'),
                        str(BASE), str(cls.inspector)], check=True,
                       capture_output=True, text=True,
                       env={**os.environ, 'CC': compiler})
        cls.ro = C.CDLL(str(cls.inspector))
        cls.ro.lh_ro_model.argtypes = [C.c_void_p, PTR]
        cls.ro.lh_ro_model.restype = None
        cls.ro.lh_ro_model_fingerprint.argtypes = [C.c_void_p]
        cls.ro.lh_ro_model_fingerprint.restype = C.c_uint64
        cls.ro.lh_ro_ground_contacts.argtypes = [C.c_void_p, C.c_int, PTR, C.c_int]
        cls.ro.lh_ro_ground_contacts.restype = C.c_int

    def setUp(self):
        self.assertEqual(hashlib.sha256(HELPER.read_bytes()).hexdigest(), PRESET['helperSHA256'])
        self.assertEqual(hashlib.sha256((BASE/'source-model/humanoid_high_freq.xml').read_bytes()).hexdigest(),
                         PRESET['sourceModelSHA256'])
        self.w = World(BASE, HELPER)
        self.addCleanup(self.w.close)
        self.w.restore(BASE/'slow-continuation/final.bin')
        self.before = checkpoint_bytes(self.w)
        self.counter = self.w.l.lh_dim(self.w.h, 6)
        self.assertEqual(self.counter, 0)
        self.model_fingerprint = self.ro.lh_ro_model_fingerprint(self.w.h)

    def tearDown(self):
        self.assertEqual(checkpoint_bytes(self.w), self.before)
        self.assertEqual(self.w.l.lh_dim(self.w.h, 6), self.counter)
        self.assertEqual(self.ro.lh_ro_model_fingerprint(self.w.h), self.model_fingerprint)

    def contacts(self, fresh):
        out = np.zeros(CAPACITY)
        count = self.ro.lh_ro_ground_contacts(self.w.h, int(fresh), ptr(out), CAPACITY)
        self.assertGreaterEqual(count, 0)
        self.assertLessEqual(count, 64)
        self.assertEqual(count, out[0])
        self.assertEqual(out[1], self.w.l.lh_time(self.w.h))
        self.assertEqual(out[2], int(fresh))
        return out, out[HEADER:HEADER+STRIDE*count].reshape(count, STRIDE)

    def test_only_three_readonly_exports_and_no_integration_import(self):
        defined = subprocess.check_output([self.nm, '-D', '--defined-only', str(self.inspector)], text=True)
        self.assertEqual({line.split()[-1] for line in defined.splitlines() if line.strip()}, EXPORTS)
        undefined = subprocess.check_output([self.nm, '-D', '--undefined-only', str(self.inspector)], text=True)
        native_imports = {line.split()[-1].split('@')[0] for line in undefined.splitlines()
                          if line.strip() and line.split()[-1].startswith(('mj_', 'mju_'))}
        self.assertEqual(native_imports, {
            'mj_version', 'mj_copyData', 'mj_makeData', 'mj_deleteData',
            'mj_fwdActuation', 'mj_fwdAcceleration', 'mj_fwdConstraint',
            'mj_contactForce', 'mj_jac', 'mju_dot'})

    def test_original_compiled_options_are_defaults_and_pure(self):
        out = np.zeros(22)
        self.ro.lh_ro_model(self.w.h, ptr(out))
        expected = {0: 213, 1: .00125, 2: 1., 3: 0, 4: 2, 5: 100,
                    6: 1e-8, 7: 0, 8: 1e-6, 9: 0, 10: 0, 11: 0,
                    12: 20, 13: 27, 14: 0.}
        for index, value in expected.items():
            with self.subTest(option_index=index):
                self.assertEqual(out[index], value)
        np.testing.assert_array_equal(out[15:17], [.02, 1.])
        np.testing.assert_array_equal(out[17:22], [.9, .95, .001, .5, 2.])

    def test_cached_geometry_does_not_claim_stale_force_pairing(self):
        _, contacts = self.contacts(False)
        self.assertGreater(len(contacts), 0)
        for contact in contacts:
            self.assertTrue(np.isnan(contact[22:28]).all())
            rows = min(10, int(contact[61]))
            self.assertTrue(np.isnan(contact[92:92+rows]).all())
            np.testing.assert_array_equal(contact[102:102+rows], -np.ones(rows))

    def test_fresh_response_matches_exact_pinned_v9_without_steps(self):
        fresh, contacts = self.contacts(True)
        self.assertGreater(len(contacts), 0)
        self.w.l.lh_motor_response.argtypes = [C.c_void_p, PTR, PTR]
        self.w.l.lh_motor_response.restype = None
        held = np.ascontiguousarray(self.w.arr(2, (21,)).copy())
        response = self.w.read('lh_motor_response', (33,), ptr(held))
        np.testing.assert_array_equal(fresh[5:32], response[:27])
        foot_bodies = [self.w.ids['left_foot'], self.w.ids['right_foot']]
        net_forces = np.zeros((2, 3))
        for contact in contacts:
            body = int(contact[1])
            geom1 = int(contact[2])
            geom1_body = int(self.w.read('lh_geom', (17,), geom1)[0])
            sign = 1. if geom1_body == 0 else -1.
            world_force = sign*contact[13:22].reshape(3, 3).T@contact[22:25]
            if body in foot_bodies:
                net_forces[foot_bodies.index(body)] += world_force
            self.assertEqual(int(contact[4]), 3)
            np.testing.assert_array_equal(contact[28:33], [1., 1., .005, .0001, .0001])
            self.assertTrue(np.isfinite(contact[22:28]).all())
            self.assertTrue(np.isfinite(contact[40:49]).all())
        np.testing.assert_allclose(net_forces, response[27:].reshape(2, 3), atol=1e-12, rtol=0.)


if __name__ == '__main__':
    unittest.main()

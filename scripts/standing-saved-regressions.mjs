import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import RAPIER from '@dimforge/rapier3d-compat';
import { captureBodies, json } from './coordinated-standing-evidence.mjs';
import { sha256 } from './capture-physics-baseline.mjs';

const directory=resolve(process.argv[2]), results=[];
const { createEmbodiedCharacter }=await import(pathToFileURL(join(directory,'original-source/src/character/index.ts')).href);
for(const [name,heading,tick] of [['h66-long-0',0,978],['h69-short-1',Math.PI/3,621],['h69-short-2',-Math.PI/4,497]]) {
  const row=JSON.parse(readFileSync(join(directory,`${name}-source-row.json`))), bytes=readFileSync(join(directory,`${name}-source-state.bin`));
  assert.equal(row.tick,tick);assert.equal(sha256(bytes),row.snapshotSha256);
  const c=await createEmbodiedCharacter('canvas2d',{heading});
  const handles=[...c.ragdollBodies].map(([id,b])=>[id,b.handle]), checks=[];
  const feasible=row.cases.filter(q=>q.finite&&q.withinOtherSpeedBounds&&q.maxFootAngular<=0.5).sort((a,b)=>a.coupledScore-b.coupledScore)[0];
  try {
    for(const [kind,query] of [['baseline',row.baseline],['retained',row.best],...(feasible?[['physical-candidate',feasible],['physical-repeat',feasible]]:[])]) {
      const world=RAPIER.World.restoreSnapshot(bytes), queue=new RAPIER.EventQueue(true);
      try {
        assert.deepEqual(captureBodies(world,handles),row.initial);
        row.axes.forEach((axis,i)=>{
          const delta=query.deltaTorqueNm[i];assert.ok(Number.isFinite(delta)&&Math.abs(delta)<=axis.unchangedTorqueCeilingNm);
          if(delta!==0)world.impulseJoints.raw.jointConfigureMotor(axis.handle,axis.abiAxis,axis.targetPosition,axis.targetVelocity+delta/axis.damping,axis.stiffness,axis.damping);
        });
        world.step(queue,c.physicsHooks);
        const bodies=captureBodies(world,handles), hash=sha256(JSON.stringify(bodies));
        assert.equal(hash,query.predictedBodySha256);
        if(kind==='retained')assert.deepEqual(bodies,row.actual);
        checks.push({kind,query:query.name,outputSha256:hash,exactBodies:25});
      }finally{queue.free();world.free();}
    }
  }finally{c.dispose();}
  results.push({name,heading,tick,checks});
}
json(join(directory,'replay-result.json'),{status:'pass',results,
  qualification:'Replayed native saved queries on archived original production source. Original prehistories and their prefix digests are retained in H71 provenance, not regenerated by this operation. No claim that current candidate commands match historical commands.'});
console.log(JSON.stringify({status:'pass',checks:results.reduce((s,r)=>s+r.checks.length,0)}));
